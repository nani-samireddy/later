#!/usr/bin/env python3
"""Verify Android backup pickers; restore preview is canceled, never committed."""
import re
import subprocess
import time
import xml.etree.ElementTree as ET
from pathlib import Path
from verify_camera_android import android, DEVICE


def nodes():
    for _ in range(10):
        android('shell', 'uiautomator', 'dump', '/sdcard/later-backup-qa.xml')
        try:
            return list(ET.fromstring(android('exec-out', 'cat', '/sdcard/later-backup-qa.xml')).iter('node'))
        except ET.ParseError:
            time.sleep(.5)
    raise RuntimeError('DocumentsUI accessibility did not become available')


def tap(node):
    a, b, c, d = map(int, re.findall(r'\d+', node.get('bounds', '')))
    android('shell', 'input', 'tap', str((a+c)//2), str((b+d)//2))


def downloads():
    current = nodes()
    menu = next((n for n in current if n.get('content-desc', '').lower() in
                 ['show roots', 'show navigation menu', 'show navigation drawer']), None)
    if menu is not None:
        tap(menu)
        current = nodes()
    root = next((n for n in current if n.get('text') == 'Downloads'), None)
    if root is not None:
        tap(root)
    return nodes()


def export(filename):
    current = downloads()
    field = next((n for n in current if n.get('class') == 'android.widget.EditText'), None)
    if field is None:
        raise RuntimeError('Save picker filename field was not found')
    tap(field)
    android('shell', 'input', 'keyevent', '123', *(['67'] * len(field.get('text', ''))))
    android('shell', 'input', 'text', filename)
    current = nodes()
    save = next((n for n in current if n.get('text', '').lower() == 'save'), None)
    if save is None:
        raise RuntimeError('Save picker action was not found')
    tap(save)


def choose(filename):
    current = downloads()
    for _ in range(10):
        # DocumentsUI may append the standard gzip extension after writing.
        file = next((n for n in current if n.get('text') in [filename, filename + '.gz']), None)
        if file is not None:
            tap(file)
            return
        time.sleep(.5)
        current = nodes()
    raise RuntimeError('Exported QA backup was not visible in Downloads')


def main():
    root = Path(__file__).resolve().parents[1]
    filename = f'later-native-qa-{int(time.time()*1000)}.laterbackup'
    print(f'QA backup filename: {filename}', flush=True)
    process = subprocess.Popen(['flutter', 'test', '-d', DEVICE, '--no-pub', '--no-uninstall',
                                'integration_test/backup_picker_android_test.dart'], cwd=root,
                               stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True, bufsize=1)
    try:
        for line in process.stdout:
            print(line, end='', flush=True)
            if 'QA_BACKUP_EXPORT' in line:
                export(filename)
            elif 'QA_BACKUP_IMPORT' in line:
                choose(filename)
        if process.wait() != 0:
            raise RuntimeError('Backup picker verification failed')
    finally:
        if process.poll() is None:
            process.terminate()
            process.wait(timeout=30)
        # Only the unique file generated by this run is removed.
        android('shell', 'rm', '-f', '/sdcard/Download/' + filename)
        android('shell', 'rm', '-f', '/sdcard/Download/' + filename + '.gz')


if __name__ == '__main__':
    main()
